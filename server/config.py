# -*- coding: utf-8 -*-
"""
异地之约 · 服务端配置

所有可调参数集中在这里，改完重启服务即可生效。
"""

import os

# ----------------------------------------------------------------------
# 网络
# ----------------------------------------------------------------------

# 监听地址。0.0.0.0 表示监听所有网卡（内网穿透/frp 需要这样）
HOST = "0.0.0.0"

# 监听端口，必须与 APP 设置页里的端口一致
PORT = 9527

# 等待客户端发 auth 的超时（秒）。超时未认证直接断开，防扫描
AUTH_TIMEOUT = 10

# 已认证连接的读超时（秒）。客户端每 30 秒发一次 ping，
# 这里给 3 倍余量；超时说明链路已死，回收连接
SOCKET_TIMEOUT = 120

# 单帧最大字节数，与客户端 Protocol.MAX_FRAME_BYTES 保持一致
MAX_PAYLOAD = 1024 * 1024

# 单张头像的最大字节数（客户端上传的是 256x256 JPEG，通常 10~30 KB）
# 留足余量，同时防止有人用头像通道塞大文件把内存和磁盘撑爆
MAX_AVATAR_BYTES = 512 * 1024

# 单机最大并发连接数（个人使用，32 足够；防呆保底）
MAX_CONNECTIONS = 32

# ----------------------------------------------------------------------
# 存储
# ----------------------------------------------------------------------

# 数据库文件路径。默认放在脚本同级的 data/ 目录下
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DB_PATH = os.path.join(BASE_DIR, "data", "baobao.db")

# 历史数据保留天数，超过的会被后台清理线程删除；设为 0 表示永久保留
HISTORY_RETENTION_DAYS = 30

# 清理线程运行间隔（秒）
CLEANUP_INTERVAL = 6 * 3600

# ----------------------------------------------------------------------
# 加密（必须与客户端 CryptoUtils.kt 完全一致，否则解不开）
# ----------------------------------------------------------------------

# 固定盐，UTF-8 字节
SALT = b"yuanzhiyue_salt"

# PBKDF2 迭代次数
PBKDF2_ITERATIONS = 10_000

# 派生密钥长度（字节）—— 32 字节 = AES-256
KEY_LENGTH = 32

# GCM 认证标签长度（字节）
GCM_TAG_BYTES = 16

# GCM IV 长度（字节）
GCM_IV_BYTES = 12

# ----------------------------------------------------------------------
# 历史查询
# ----------------------------------------------------------------------

# 客户端不指定 limit 时返回多少条
HISTORY_DEFAULT_LIMIT = 200

# 客户端指定的上限，防止一次拉爆内存
HISTORY_MAX_LIMIT = 1000

# ----------------------------------------------------------------------
# 日志
# ----------------------------------------------------------------------

LOG_LEVEL = "INFO"          # DEBUG / INFO / WARNING / ERROR
LOG_TO_FILE = True          # 是否同时写入 data/server.log
LOG_FILE = os.path.join(BASE_DIR, "data", "server.log")
LOG_MAX_BYTES = 5 * 1024 * 1024
LOG_BACKUP_COUNT = 3
